static (double x1, double x2) bracket_minimum(Func<double, double> f, double x= 0, double s=1e-2, double k=2.0)
{
    var (a, ya) = (x, f(x));
    var (b, yb) = (a + s, f(a + s));
    if (yb > ya)
        (a, b, ya, yb, s) = (b, a, yb, ya, -s);

    while (true)
    {
        var (c, yc) = (b + s, f(b + s));
        if (yc > yb)
            return a < c ? (a, c) : (c, a);
        (a, ya, b, yb, s) = (b, yb, c, yc, s*k);
    }
}




